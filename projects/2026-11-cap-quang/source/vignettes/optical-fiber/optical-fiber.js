// Longitudinal cutaway along X. The red line marks the core/cladding interface, not a mirror.
export function opticalFiber(kit, opts = {}) {
  const { THREE, PALETTE } = kit;
  const group = new THREE.Group();
  group.name = 'optical-fiber';
  const variants = {};
  for (const [name, bend] of [['straight', 0], ['bent', 0.36]]) {
    const section = new THREE.Group();
    section.name = name;
    const curve = new THREE.CatmullRomCurve3([
      new THREE.Vector3(-2, 0, 0), new THREE.Vector3(-1, 0, 0),
      new THREE.Vector3(0, bend, 0), new THREE.Vector3(1, bend, 0), new THREE.Vector3(2, bend, 0)
    ]);
    // Open the front half of the cladding so the interior remains visible.
    const cladding = new THREE.Mesh(new THREE.TubeGeometry(curve, 48, 0.45, 16, false), kit.toon(PALETTE.card));
    // A half-cylinder cutaway generated by retaining the rear-facing tube triangles.
    const geo = cladding.geometry;
    const index = geo.index.array;
    const kept = [];
    for (let i = 0; i < index.length; i += 3) {
      const a = index[i], b = index[i + 1], c = index[i + 2];
      const pos = geo.attributes.position;
      if ((pos.getZ(a) + pos.getZ(b) + pos.getZ(c)) / 3 <= 0.02) kept.push(a, b, c);
    }
    geo.setIndex(kept);
    cladding.material.side = THREE.DoubleSide;
    cladding.name = 'cladding-cutaway';
    section.add(cladding);
    for (const side of [-1, 1]) {
      const points = curve.points.map(p => new THREE.Vector3(p.x, p.y + side * 0.25, 0.02));
      const edge = new THREE.CatmullRomCurve3(points);
      const boundary = new THREE.Mesh(new THREE.TubeGeometry(edge, 48, 0.025, 6, false), kit.toon(PALETTE.accent));
      boundary.name = 'reflection-boundary';
      section.add(boundary);
    }
    const core = new THREE.Mesh(new THREE.TubeGeometry(curve, 48, 0.23, 12, false), kit.toon(PALETTE.shade));
    core.name = 'core';
    section.add(core);
    group.add(section);
    variants[name] = section;
  }
  kit.ink(group);
  function update(t, state = {}) {
    const bent = state.bent ?? opts.bent ?? false;
    variants.straight.visible = !bent;
    variants.bent.visible = !!bent;
  }
  update(0);
  return { group, hero: group, update };
}
